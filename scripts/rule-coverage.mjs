#!/usr/bin/env node
/**
 * Generate docs/rule-coverage.md: every assertion id in the official PINT AE
 * Schematron, marked as covered by a native TypeScript rule or by the
 * Schematron only. Run with `--check` to fail (exit 1) if the committed file is
 * out of date. Requires the ae package to be built (reads its rule set).
 *
 *   node scripts/rule-coverage.mjs           # write docs/rule-coverage.md
 *   node scripts/rule-coverage.mjs --check   # verify it is up to date
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const schDir = resolve(root, 'spec/pint-ae-billing');
const outFile = resolve(root, 'docs/rule-coverage.md');

const schematronFiles = [
  'trn-invoice/schematron/PINT-UBL-validation-preprocessed.sch',
  'trn-invoice/schematron/PINT-jurisdiction-aligned-rules.sch',
  'trn-creditnote/schematron/PINT-UBL-validation-preprocessed.sch',
  'trn-creditnote/schematron/PINT-jurisdiction-aligned-rules.sch',
];

/** All assertion ids across the official Schematron files. */
function schematronIds() {
  const ids = new Set();
  for (const file of schematronFiles) {
    const sch = readFileSync(resolve(schDir, file), 'utf8');
    for (const m of sch.matchAll(/<assert\b[^>]*\sid="([^"]+)"/g)) ids.add(m[1]);
  }
  return [...ids].sort((a, b) => a.localeCompare(b, 'en'));
}

async function nativeIds() {
  const mod = await import(pathToFileURL(resolve(root, 'packages/ae/dist/index.js')).href);
  return new Set(mod.PintAE.rules.map((r) => r.id));
}

function render(all, native) {
  const nativeCount = all.filter((id) => native.has(id)).length;
  const lines = [];
  lines.push('# Rule coverage');
  lines.push('');
  lines.push('Coverage of the official OpenPeppol PINT AE Billing v1.0.3 Schematron. Every');
  lines.push('document is validated against the full Schematron in `full` mode; a subset is');
  lines.push('also implemented as native TypeScript rules for `fast` mode and the builder.');
  lines.push('');
  lines.push('> Generated by `scripts/rule-coverage.mjs` — do not edit by hand.');
  lines.push('');
  lines.push(`- **Official Schematron:** ${all.length} / ${all.length} assertions.`);
  lines.push(`- **Native TypeScript rules:** ${nativeCount} / ${all.length} assertions.`);
  lines.push('');
  lines.push('| Rule ID | Native | Schematron |');
  lines.push('| --- | :---: | :---: |');
  for (const id of all) {
    lines.push(`| \`${id}\` | ${native.has(id) ? '✅' : ''} | ✅ |`);
  }
  lines.push('');
  return lines.join('\n');
}

const all = schematronIds();
const native = await nativeIds();
const content = render(all, native);

const check = process.argv.includes('--check');
if (check) {
  const existing = (() => {
    try {
      return readFileSync(outFile, 'utf8');
    } catch {
      return '';
    }
  })();
  if (existing !== content) {
    process.stderr.write(
      'docs/rule-coverage.md is out of date. Run: node scripts/rule-coverage.mjs\n',
    );
    process.exit(1);
  }
  process.stdout.write('docs/rule-coverage.md is up to date.\n');
} else {
  writeFileSync(outFile, content);
  const nativeCount = all.filter((id) => native.has(id)).length;
  process.stdout.write(`Wrote ${outFile} (native ${nativeCount} / ${all.length}).\n`);
}
