#!/usr/bin/env node
/**
 * Extract code lists from the vendored genericode (`.gc`) files under `spec/`
 * into committed JSON arrays, so the native code-list rules never hand-type a
 * code. Generated artifacts — regenerate with:
 *   node scripts/build-codelists.mjs
 * CI regenerates and diffs these so they always match the vendored spec.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const codelistDir = resolve(root, 'spec/pint-ae-billing/trn-invoice/codelist');
const outDir = resolve(root, 'packages/ae/src/codelists/generated');

/** Output name -> genericode file. The identifier column is `code` or `id`. */
const lists = {
  currency: 'ISO4217.gc',
  country: 'ISO3166.gc',
  unit: 'UNECERec20.gc',
};

/** Pull the identifier-column values out of a genericode document. */
function extractCodes(gc) {
  const re = /<gc:Value ColumnRef="(?:code|id)">\s*<gc:SimpleValue>([^<]*)<\/gc:SimpleValue>/g;
  const codes = [];
  for (const match of gc.matchAll(re)) codes.push(match[1]);
  return [...new Set(codes)].sort();
}

mkdirSync(outDir, { recursive: true });

for (const [name, file] of Object.entries(lists)) {
  const gc = readFileSync(resolve(codelistDir, file), 'utf8');
  const codes = extractCodes(gc);
  if (codes.length === 0) throw new Error(`No codes extracted from ${file}`);
  const body =
    `// Generated by scripts/build-codelists.mjs from spec/.../${file} — do not edit.\n` +
    `const codes: readonly string[] = ${JSON.stringify(codes)};\n` +
    `export default codes;\n`;
  writeFileSync(resolve(outDir, `${name}.ts`), body);
  process.stdout.write(`${name}: ${codes.length} codes from ${file}\n`);
}
